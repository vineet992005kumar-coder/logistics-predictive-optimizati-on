import json
import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from scipy.optimize import linprog
from scipy.sparse import lil_matrix
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import GradientBoostingRegressor, RandomForestRegressor
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import KFold, RandomizedSearchCV, cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.tree import DecisionTreeRegressor

SEED = 42
rng = np.random.default_rng(SEED)
os.makedirs("charts", exist_ok=True)
sns.set_theme(style="whitegrid")
results = {}


# ------------------------------------------------------------
# 1. Problem definition and data simulation
# Target: delivery_days (regression). Cost is predicted too, for optimisation.
# ------------------------------------------------------------
def make_dataset(n=6000):
    date = pd.Timestamp("2025-01-01") + pd.to_timedelta(rng.integers(0, 365, n), unit="D")
    hub = rng.choice(["Hub A", "Hub B", "Hub C"], n, p=[0.40, 0.35, 0.25])
    carrier = rng.choice(["FastShip", "QuickMove", "CityCourier"], n, p=[0.40, 0.35, 0.25])
    mode = rng.choice(["Road", "Rail", "Air"], n, p=[0.65, 0.20, 0.15])

    distance = np.where(mode == "Road", rng.gamma(2.5, 120, n),
               np.where(mode == "Rail", rng.gamma(3.0, 250, n), rng.gamma(3.0, 450, n)))
    distance = np.clip(distance, 20, 3500)
    weight = rng.gamma(2.2, 14, n).clip(1, 250)

    rate = {"Road": 0.9, "Rail": 0.55, "Air": 3.4}
    cost = (np.array([rate[m] for m in mode]) * distance + 1.2 * weight + 25
            + rng.normal(0, 40, n)).clip(15)

    speed = {"Road": 600, "Rail": 450, "Air": 1500}
    days = distance / np.array([speed[m] for m in mode]) + 1 + rng.gamma(1.5, 0.6, n)
    month = pd.DatetimeIndex(date).month
    peak = np.isin(month, [10, 11, 12])
    days = days + peak * rng.gamma(2.0, 0.5, n)
    days = days + (carrier == "CityCourier") * rng.gamma(2.0, 0.45, n)
    days = days + (hub == "Hub C") * rng.gamma(1.5, 0.35, n)

    df = pd.DataFrame({
        "hub": hub, "carrier": carrier, "mode": mode,
        "distance_km": distance.round(1), "weight_kg": weight.round(1),
        "month": month, "weekday": pd.DatetimeIndex(date).dayofweek,
        "is_peak": peak.astype(int),
        "promised_days": 4.5 + (distance > 1000) * 2,
        "transport_cost": cost.round(2), "delivery_days": days.round(2),
    })
    return df


df = make_dataset()
cat = ["hub", "carrier", "mode"]
num = ["distance_km", "weight_kg", "month", "weekday", "is_peak"]
features = cat + num
target = "delivery_days"
print("Dataset:", df.shape)

# ------------------------------------------------------------
# 2. Data preparation: train / test split + preprocessing pipeline
# ------------------------------------------------------------
X, y = df[features], df[target]
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=SEED)
print("Train:", X_train.shape, "Test:", X_test.shape)


def make_pipe(model, scale=False):
    pre = ColumnTransformer([
        ("cat", OneHotEncoder(handle_unknown="ignore"), cat),
        ("num", StandardScaler() if scale else "passthrough", num),
    ])
    return Pipeline([("prep", pre), ("model", model)])


# ------------------------------------------------------------
# 3. Model selection with 5-fold cross-validation
# ------------------------------------------------------------
candidates = {
    "Linear Regression": make_pipe(LinearRegression(), scale=True),
    "Decision Tree": make_pipe(DecisionTreeRegressor(max_depth=6, random_state=SEED)),
    "Random Forest": make_pipe(RandomForestRegressor(n_estimators=200, n_jobs=-1, random_state=SEED)),
    "Gradient Boosting": make_pipe(GradientBoostingRegressor(random_state=SEED)),
}
kf = KFold(n_splits=5, shuffle=True, random_state=SEED)
cv_rows = []
for name, pipe in candidates.items():
    rmse = -cross_val_score(pipe, X_train, y_train, cv=kf, scoring="neg_root_mean_squared_error")
    r2 = cross_val_score(pipe, X_train, y_train, cv=kf, scoring="r2")
    cv_rows.append({"model": name, "cv_rmse": rmse.mean(), "cv_rmse_std": rmse.std(), "cv_r2": r2.mean()})
cv = pd.DataFrame(cv_rows).sort_values("cv_rmse")
print("\nCross-validation results:\n", cv.round(3).to_string(index=False))
results["cv"] = cv.round(3).to_dict("records")

# ------------------------------------------------------------
# 4. Hyperparameter tuning (randomised search) on the best model family
# ------------------------------------------------------------
param_dist = {
    "model__n_estimators": [100, 200, 300, 400],
    "model__learning_rate": [0.03, 0.05, 0.1, 0.15],
    "model__max_depth": [2, 3, 4, 5],
    "model__min_samples_leaf": [1, 5, 10, 20],
    "model__subsample": [0.7, 0.85, 1.0],
}
search = RandomizedSearchCV(candidates["Gradient Boosting"], param_dist, n_iter=15, cv=3,
                            scoring="neg_root_mean_squared_error", random_state=SEED, n_jobs=-1)
search.fit(X_train, y_train)
best = search.best_estimator_
print("\nBest parameters:", search.best_params_)
results["best_params"] = {k.replace("model__", ""): v for k, v in search.best_params_.items()}

# ------------------------------------------------------------
# 5. Evaluation on the untouched test set
# ------------------------------------------------------------
def evaluate(model):
    p = model.predict(X_test)
    return {"MAE": mean_absolute_error(y_test, p),
            "RMSE": np.sqrt(mean_squared_error(y_test, p)),
            "R2": r2_score(y_test, p)}, p


test_rows = []
for name, pipe in candidates.items():
    pipe.fit(X_train, y_train)
    m, _ = evaluate(pipe)
    test_rows.append({"model": name, **m})
m_best, pred = evaluate(best)
test_rows.append({"model": "Gradient Boosting (tuned)", **m_best})
test_df = pd.DataFrame(test_rows)
print("\nTest set results:\n", test_df.round(3).to_string(index=False))
results["test"] = test_df.round(3).to_dict("records")
results["baseline_mae"] = float(mean_absolute_error(y_test, np.full(len(y_test), y_train.mean())))

# ------------------------------------------------------------
# 6. Charts
# ------------------------------------------------------------
def save(name):
    plt.tight_layout(); plt.savefig(f"charts/{name}.png", dpi=150); plt.close()

plt.figure(figsize=(8, 4.5))
order = cv.sort_values("cv_rmse")
sns.barplot(data=order, x="cv_rmse", y="model", color="#2E74B5")
plt.xlabel("Cross-validated RMSE (days, lower is better)"); plt.ylabel("")
plt.title("Model Comparison (5-fold cross-validation)"); save("01_model_comparison")

plt.figure(figsize=(6.5, 5.5))
plt.scatter(y_test, pred, s=10, alpha=0.4, color="#2E74B5")
lim = [0, max(y_test.max(), pred.max()) + 0.5]
plt.plot(lim, lim, "r--", label="Perfect prediction")
plt.xlabel("Actual delivery time (days)"); plt.ylabel("Predicted delivery time (days)")
plt.title("Actual vs Predicted (Test Set)"); plt.legend(); save("02_actual_vs_predicted")

resid = y_test - pred
plt.figure(figsize=(8, 4.5))
sns.histplot(resid, bins=40, kde=True, color="#70AD47")
plt.axvline(0, color="red", ls="--")
plt.xlabel("Prediction error (actual - predicted, days)"); plt.title("Distribution of Residuals")
save("03_residuals")

pi = permutation_importance(best, X_test, y_test, n_repeats=8, random_state=SEED,
                            scoring="neg_root_mean_squared_error", n_jobs=-1)
imp = pd.Series(pi.importances_mean, index=features).sort_values()
plt.figure(figsize=(8, 4.5))
imp.plot(kind="barh", color="#ED7D31")
plt.xlabel("Increase in RMSE when feature is shuffled"); plt.title("Feature Importance (Permutation)")
save("04_feature_importance")
results["importance"] = imp.sort_values(ascending=False).round(3).to_dict()

# ------------------------------------------------------------
# 7. Optimisation A: cost-minimising transport mode choice
# Only shipments currently sent by AIR are re-evaluated (air is the most expensive mode).
# Rule: move to the cheapest mode whose predicted time is at least 1 day inside the promise.
# ------------------------------------------------------------
cost_model = make_pipe(GradientBoostingRegressor(random_state=SEED))
cost_model.fit(X_train, df.loc[X_train.index, "transport_cost"])
cost_pred = cost_model.predict(X_test)
results["cost_model_r2"] = float(r2_score(df.loc[X_test.index, "transport_cost"], cost_pred))

scen = X_test.copy().reset_index(drop=True)
promised = df.loc[X_test.index, "promised_days"].values
modes = ["Road", "Rail", "Air"]
days_by_mode, cost_by_mode = {}, {}
for m in modes:
    s = scen.copy(); s["mode"] = m
    days_by_mode[m] = best.predict(s)
    cost_by_mode[m] = cost_model.predict(s)
D = np.column_stack([days_by_mode[m] for m in modes])
C = np.column_stack([cost_by_mode[m] for m in modes])
BUFFER = 1.0                                            # safety margin in days (about 1 RMSE)
feasible = D <= (promised[:, None] - BUFFER)
masked_cost = np.where(feasible, C, np.inf)
cur_idx = scen["mode"].map({m: i for i, m in enumerate(modes)}).values
best_alt = np.where(feasible.any(axis=1), masked_cost.argmin(axis=1), cur_idx)
choice = np.where(cur_idx == modes.index("Air"), best_alt, cur_idx)   # only Air shipments change
rows = np.arange(len(scen))
cur_cost, new_cost = C[rows, cur_idx].sum(), C[rows, choice].sum()
cur_ontime = (D[rows, cur_idx] <= promised).mean()
new_ontime = (D[rows, choice] <= promised).mean()
switched = (choice != cur_idx).mean()
print("\n[Mode optimisation] predicted cost: %.0f -> %.0f (%.1f%% saving)" % (cur_cost, new_cost, 100 * (1 - new_cost / cur_cost)))
print("On-time (predicted): %.1f%% -> %.1f%%, shipments switched: %.1f%%" % (100 * cur_ontime, 100 * new_ontime, 100 * switched))
results["mode_opt"] = {"cost_before": float(cur_cost), "cost_after": float(new_cost),
                       "saving_pct": float(100 * (1 - new_cost / cur_cost)),
                       "ontime_before": float(100 * cur_ontime), "ontime_after": float(100 * new_ontime),
                       "switched_pct": float(100 * switched)}
share_before = pd.Series(scen["mode"]).value_counts(normalize=True).reindex(modes).fillna(0) * 100
share_after = pd.Series(np.array(modes)[choice]).value_counts(normalize=True).reindex(modes).fillna(0) * 100
results["mode_share"] = {"before": share_before.round(1).to_dict(), "after": share_after.round(1).to_dict()}
cost_before_mode = pd.Series(C[rows, cur_idx]).groupby(scen["mode"].values).sum().reindex(modes)
cost_after_mode = pd.Series(C[rows, choice]).groupby(np.array(modes)[choice]).sum().reindex(modes).fillna(0)
results["cost_by_mode"] = {"before": cost_before_mode.round(0).to_dict(), "after": cost_after_mode.round(0).to_dict()}

fig, ax = plt.subplots(1, 2, figsize=(10, 4.2))
x = np.arange(3); w = 0.38
ax[0].bar(x - w / 2, share_before.values, w, label="Current", color="#9DC3E6")
ax[0].bar(x + w / 2, share_after.values, w, label="Optimised", color="#2E74B5")
ax[0].set_xticks(x); ax[0].set_xticklabels(modes); ax[0].set_ylabel("% of shipments"); ax[0].set_title("Mode Mix"); ax[0].legend()
ax[1].bar(x - w / 2, cost_before_mode.values / 1000, w, label="Current", color="#F4B183")
ax[1].bar(x + w / 2, cost_after_mode.values / 1000, w, label="Optimised", color="#C55A11")
ax[1].set_xticks(x); ax[1].set_xticklabels(modes); ax[1].set_ylabel("Predicted total cost (thousands)"); ax[1].set_title("Cost by Mode"); ax[1].legend()
plt.suptitle("Optimisation A: Cost-Minimising Mode Choice"); save("05_mode_optimisation")

# ------------------------------------------------------------
# 8. Optimisation B: carrier allocation with capacity limits (linear programming)
# Minimise total predicted delivery days; no carrier may handle more than 45%.
# ------------------------------------------------------------
carriers = ["FastShip", "QuickMove", "CityCourier"]
T = np.column_stack([best.predict(scen.assign(carrier=c)) for c in carriers])
n, k = T.shape
A_eq = lil_matrix((n, n * k)); A_ub = lil_matrix((k, n * k))
for i in range(n):
    for j in range(k):
        A_eq[i, i * k + j] = 1
        A_ub[j, i * k + j] = 1
res = linprog(T.ravel(), A_ub=A_ub.tocsr(), b_ub=np.full(k, 0.45 * n),
              A_eq=A_eq.tocsr(), b_eq=np.ones(n), bounds=(0, 1), method="highs")
assign = res.x.reshape(n, k).argmax(axis=1)
cur_c = scen["carrier"].map({c: i for i, c in enumerate(carriers)}).values
days_before, days_after = T[rows, cur_c], T[rows, assign]
late_before = (days_before > promised).mean(); late_after = (days_after > promised).mean()
print("\n[Carrier allocation] avg days: %.2f -> %.2f ; predicted late rate: %.1f%% -> %.1f%%" %
      (days_before.mean(), days_after.mean(), 100 * late_before, 100 * late_after))
sh_b = pd.Series(scen["carrier"]).value_counts(normalize=True).reindex(carriers) * 100
sh_a = pd.Series(np.array(carriers)[assign]).value_counts(normalize=True).reindex(carriers).fillna(0) * 100
results["carrier_opt"] = {"days_before": float(days_before.mean()), "days_after": float(days_after.mean()),
                          "late_before": float(100 * late_before), "late_after": float(100 * late_after),
                          "share_before": sh_b.round(1).to_dict(), "share_after": sh_a.round(1).to_dict()}

fig, ax = plt.subplots(1, 2, figsize=(10, 4.2))
ax[0].bar(x - w / 2, sh_b.values, w, label="Current", color="#A9D18E")
ax[0].bar(x + w / 2, sh_a.values, w, label="Optimised", color="#548235")
ax[0].set_xticks(x); ax[0].set_xticklabels(carriers); ax[0].set_ylabel("% of shipments"); ax[0].set_title("Carrier Share"); ax[0].legend()
ax[1].bar(["Current", "Optimised"], [100 * late_before, 100 * late_after], color=["#F4B183", "#70AD47"])
ax[1].set_ylabel("Predicted late shipments (%)"); ax[1].set_title("Predicted Late Rate")
plt.suptitle("Optimisation B: Carrier Allocation (LP, max 45% per carrier)"); save("06_carrier_optimisation")

